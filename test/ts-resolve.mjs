// Lets `node --test` run the TypeScript sources directly (Node strips the types): the sources use
// extensionless relative imports, as the bundler expects, so try `<specifier>.ts` when Node
// cannot resolve one.
import { registerHooks } from "node:module";

registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (/^\.\.?\//.test(specifier) && !/\.[cm]?[jt]sx?$/.test(specifier)) {
        return nextResolve(`${specifier}.ts`, context);
      }
      throw error;
    }
  },
});
